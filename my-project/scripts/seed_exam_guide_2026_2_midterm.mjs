async function main() {
  const loginId = process.env.VITE_LOGIN_ID;
  const loginPw = process.env.VITE_LOGIN_PW;
  if (!loginId || !loginPw) {
    throw new Error("VITE_LOGIN_ID / VITE_LOGIN_PW 환경변수가 없습니다 (.env 확인 필요)");
  }
  await signInWithEmailAndPassword(auth, `${loginId}${LOGIN_EMAIL_DOMAIN}`, loginPw);

  // Firestore는 배열 안의 배열을 저장하지 못하므로 표의 각 행은 { cells: [...] }로 감싼다
  const slides = SLIDES.map((s) => ({
    layout: "content", subtitle: "", points: [], warning: "", images: [], table: null, seats: null,
    ...s,
    ...(s.table && { table: { headers: s.table.headers, rows: s.table.rows.map((cells) => ({ cells })) } }),
  }));
  const guide = { title: TITLE, examDate: "", slides };
  const size = Buffer.byteLength(JSON.stringify(guide));

  console.log(`제목: ${TITLE}`);
  console.log(`슬라이드 ${slides.length}장 / 문서 크기 약 ${Math.round(size / 1024)}KB (Firestore 한도 1024KB)`);
  for (const [i, s] of slides.entries()) console.log(`  ${i + 1}. ${s.icon} ${s.title}`);

  const existingSnap = await getDocs(collection(db, "examGuides"));
  if (existingSnap.docs.some((d) => d.data().title === TITLE)) {
    console.log(`\n같은 제목의 자료가 이미 있어 건너뜁니다.`);
    return;
  }

  if (!COMMIT) {
    console.log(`\n(미리보기 모드입니다. 실제로 저장하려면 --commit 옵션을 붙여 다시 실행하세요.)`);
    return;
  }

  const now = new Date().toISOString();
  const ref = await addDoc(collection(db, "examGuides"), { ...guide, createdAt: now, updatedAt: now });
  console.log(`\n완료: examGuides/${ref.id} 에 저장했습니다.`);
}

main()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error("실패:", err);
    process.exit(1);
  });
