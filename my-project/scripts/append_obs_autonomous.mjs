const ALL = [
  ...seaEntries.map((e) => ({ ...e, tag: SEA_TAG })),
  ...bookEntries.map((e) => ({ ...e, tag: BOOK_TAG })),
  ...multiEntries.map((e) => ({ ...e, tag: MULTI_TAG })),
];

async function main() {
  const studentsSnap = await getDocs(collection(db, "students"));
  const students = studentsSnap.docs.map((d) => ({ id: d.id, ...d.data() }));
  const byStudentId = new Map(students.map((s) => [String(s.studentId), s]));

  const toWrite = [];
  const skippedDup = [];
  const unmatched = [];

  for (const entry of ALL) {
    const student = byStudentId.get(entry.studentId);
    if (!student) {
      unmatched.push(`${entry.studentId} (${entry.tag})`);
      continue;
    }
    const existing = student.obsAutonomous || "";
    if (existing.includes(entry.tag)) {
      skippedDup.push(`${student.number}번 ${student.name}(${entry.studentId}) - ${entry.tag}`);
      continue;
    }
    const block = `${entry.tag} (${TODAY})\n${entry.content}`;
    const newValue = existing ? `${existing}\n\n${block}` : block;
    toWrite.push({ studentId: entry.studentId, name: student.name, number: student.number, newValue, tag: entry.tag });
  }

  console.log(`총 ${ALL.length}건 / 신규 반영 대상 ${toWrite.length}건 / 이미 반영됨(건너뜀) ${skippedDup.length}건 / 매칭 실패 ${unmatched.length}건`);
  if (unmatched.length > 0) console.log("매칭 실패:", unmatched.join(", "));
  if (skippedDup.length > 0) console.log("이미 반영됨(건너뜀):", skippedDup.join(", "));

  console.log("\n--- 반영 대상 미리보기 ---");
  for (const item of toWrite.sort((a, b) => Number(a.number) - Number(b.number))) {
    console.log(`\n■ ${item.number}번 ${item.name} (${item.studentId}) - ${item.tag}`);
  }

  console.log("\n--- ⚠️ 자동 반영하지 않음 (원본 대조 확인 필요) ---");
  for (const line of REVIEW_NEEDED) console.log(" - " + line);

  if (!COMMIT) {
    console.log(`\n(미리보기 모드입니다. 실제로 저장하려면 --commit 옵션을 붙여 다시 실행하세요.)`);
    return;
  }

  for (const item of toWrite) {
    await updateDoc(doc(db, "students", item.studentId), { obsAutonomous: item.newValue });
  }
  console.log(`\n완료: ${toWrite.length}명의 obsAutonomous에 반영했습니다.`);
}

main().catch((err) => {
  console.error("실패:", err);
  process.exit(1);
});
